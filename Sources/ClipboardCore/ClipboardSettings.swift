import Foundation

public struct ClipboardSettings: Codable, Equatable, Sendable {
    /// Max unpinned items kept.
    public var historyLimit = 300
    /// Unpinned items older than this are removed. nil = keep forever.
    public var keepDays: Int? = 30
    public var detectSecrets = true
    /// How long a detected secret stays in history (and on the clipboard).
    public var secretSeconds = 60
    /// After `secretSeconds`, also clear the system clipboard if it still holds the secret.
    public var wipeClipboard = true
    public var showSecretToast = true
    public var storeImages = true
    /// After choosing an item, paste it into the frontmost app (needs Accessibility).
    public var pasteDirectly = false
    public var hotkeyEnabled = true
    public var hotkey = "ctrl+cmd+v"
    public var ignoredApps: [AppRef] = ClipboardRules.defaultIgnoredApps

    public init() {}

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let d = ClipboardSettings()
        historyLimit = try c.decodeIfPresent(Int.self, forKey: .historyLimit) ?? d.historyLimit
        keepDays = try c.decodeIfPresent(Int.self, forKey: .keepDays) ?? (c.contains(.keepDays) ? nil : d.keepDays)
        detectSecrets = try c.decodeIfPresent(Bool.self, forKey: .detectSecrets) ?? d.detectSecrets
        secretSeconds = try c.decodeIfPresent(Int.self, forKey: .secretSeconds) ?? d.secretSeconds
        wipeClipboard = try c.decodeIfPresent(Bool.self, forKey: .wipeClipboard) ?? d.wipeClipboard
        showSecretToast = try c.decodeIfPresent(Bool.self, forKey: .showSecretToast) ?? d.showSecretToast
        storeImages = try c.decodeIfPresent(Bool.self, forKey: .storeImages) ?? d.storeImages
        pasteDirectly = try c.decodeIfPresent(Bool.self, forKey: .pasteDirectly) ?? d.pasteDirectly
        hotkeyEnabled = try c.decodeIfPresent(Bool.self, forKey: .hotkeyEnabled) ?? d.hotkeyEnabled
        hotkey = try c.decodeIfPresent(String.self, forKey: .hotkey) ?? d.hotkey
        ignoredApps = try c.decodeIfPresent([AppRef].self, forKey: .ignoredApps) ?? d.ignoredApps
    }

    // Encode keepDays explicitly as null so "forever" survives a round trip.
    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(historyLimit, forKey: .historyLimit)
        if let keepDays { try c.encode(keepDays, forKey: .keepDays) } else { try c.encodeNil(forKey: .keepDays) }
        try c.encode(detectSecrets, forKey: .detectSecrets)
        try c.encode(secretSeconds, forKey: .secretSeconds)
        try c.encode(wipeClipboard, forKey: .wipeClipboard)
        try c.encode(showSecretToast, forKey: .showSecretToast)
        try c.encode(storeImages, forKey: .storeImages)
        try c.encode(pasteDirectly, forKey: .pasteDirectly)
        try c.encode(hotkeyEnabled, forKey: .hotkeyEnabled)
        try c.encode(hotkey, forKey: .hotkey)
        try c.encode(ignoredApps, forKey: .ignoredApps)
    }

    enum CodingKeys: String, CodingKey {
        case historyLimit, keepDays, detectSecrets, secretSeconds, wipeClipboard, showSecretToast,
             storeImages, pasteDirectly, hotkeyEnabled, hotkey, ignoredApps
    }
}

public enum ClipboardRules {
    /// Pasteboard types that mean "don't record this". See nspasteboard.org.
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    public static func shouldIgnore(types: [String]) -> Bool {
        types.contains { ignoredTypes.contains($0) }
    }

    /// Password managers and similar: never recorded, even if they forget the markers above.
    public static let defaultIgnoredApps: [AppRef] = [
        AppRef(bundleID: "com.1password.1password", name: "1Password"),
        AppRef(bundleID: "com.agilebits.onepassword7", name: "1Password 7"),
        AppRef(bundleID: "com.bitwarden.desktop", name: "Bitwarden"),
        AppRef(bundleID: "com.apple.keychainaccess", name: "Keychain Access"),
        AppRef(bundleID: "com.apple.Passwords", name: "Passwords"),
        AppRef(bundleID: "org.keepassxc.keepassxc", name: "KeePassXC"),
        AppRef(bundleID: "com.lastpass.LastPass", name: "LastPass"),
        AppRef(bundleID: "com.dashlane.dashlanephonefinal", name: "Dashlane"),
        AppRef(bundleID: "me.proton.pass.electron", name: "Proton Pass"),
    ]

    /// Text longer than this isn't stored (a whole log file, a database dump).
    public static let maxTextLength = 200_000
    /// Images bigger than this aren't stored.
    public static let maxImageBytes = 8 * 1024 * 1024
}
